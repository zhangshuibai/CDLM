#!/bin/bash
# =============================================================================
# Build a CRB input set with codecorrection/generate.py (CPU only).
#
#   bash evaluation/crb/build_crb_inputs.sh --out_dir DIR [options]
#   bash evaluation/crb/build_crb_inputs.sh --help
#
# Options:
#   --out_dir DIR                          output directory (required)
#   --tokenizer fredzzp/open-dcoder-0.5B   model whose tokenizer is used for the corruption
#                                          (must be the tokenizer of the models evaluated)
#   --seed 42                              generate.py --seed
#   --nr "1 2 3 4 5"                       n_replace levels
#   --data_num 2                           corrupted variants per program
#   --datasets "human-eval human-eval+ mbpp mbpp+"
#   --error_types "operator var literal"
#   --no_deduplicate                       keep duplicate (task_id, buggy_body) items
#   --eval_jobs 8                          concurrent evaluation processes
#
# For every (dataset, error type, n_replace):
#   1. generate.py corrupts the canonical solutions:
#        DIR/buggy_datasets/<dataset>/<tag>_<error>_<data_num>_wrong_<nr>.jsonl
#      where <tag> is the basename of --tokenizer;
#   2. evaluate_code.py --map_prompt2completion --no_postprocess executes every corrupted
#      program against the tests and marks the ones that still pass (test_passed=true;
#      refine_code.py skips those):
#        DIR/buggy_datasets/<dataset>/evaluated/<tag>_<error>_<data_num>_wrong_<nr>_evaluated.jsonl
# and finally writes DIR/INPUTS.md5 and DIR/crb_inputs_meta.json (tag, settings and the
# tokenizer hash that run_crb.sh checks).  Evaluate models on the set with
#   CRB_INPUTS_DIR=DIR bash evaluation/crb/run_crb.sh <MODEL> <LABEL>
#
# The paper's var and literal files cannot be regenerated byte for byte: before the
# release generate.py iterated a set of strings, so its choices depended on
# PYTHONHASHSEED.  Environment: CRB_PYTHON (default python), CRB_OFFLINE=1,
# HF_SCRIPTS_VERSION (code_eval metric version, default v0.4.0; a module other than the
# verified one stops the build).
# =============================================================================
set -uo pipefail
{  # parsed as a whole, so editing this file cannot affect a running build
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
REPO=$(cd "$HERE/../.." && pwd)

OUT=""; TOKENIZER=fredzzp/open-dcoder-0.5B; SEED=42; NR_LIST="1 2 3 4 5"; DATA_NUM=2
DATASETS_LIST="human-eval human-eval+ mbpp mbpp+"; ERROR_TYPES_LIST="operator var literal"
DEDUP=1; EVAL_JOBS=8
usage() { awk 'NR>1 && /^#/ {print; next} NR>1 {exit}' "$0"; }
while [ $# -gt 0 ]; do
  case "$1" in
    -h|--help) usage; exit 0;;
    --out_dir) OUT=$2; shift 2;;
    --tokenizer) TOKENIZER=$2; shift 2;;
    --seed) SEED=$2; shift 2;;
    --nr) NR_LIST=$2; shift 2;;
    --data_num) DATA_NUM=$2; shift 2;;
    --datasets) DATASETS_LIST=$2; shift 2;;
    --error_types) ERROR_TYPES_LIST=$2; shift 2;;
    --no_deduplicate) DEDUP=0; shift;;
    --eval_jobs) EVAL_JOBS=$2; shift 2;;
    *) echo "unknown arg $1"; exit 2;;
  esac
done
fail() { echo "FAIL: $*"; exit 1; }
[ -n "$OUT" ] || { usage; exit 2; }
DATASETS=($DATASETS_LIST); ERROR_TYPES=($ERROR_TYPES_LIST); NR_ARR=($NR_LIST)
for d in "${DATASETS[@]}"; do case "$d" in human-eval|human-eval+|mbpp|mbpp+) ;; *) fail "bad dataset $d";; esac; done
for e in "${ERROR_TYPES[@]}"; do case "$e" in operator|var|literal) ;; *) fail "bad error type $e";; esac; done

PY=${CRB_PYTHON:-python}
command -v "$PY" >/dev/null || fail "python interpreter '$PY' not found (set CRB_PYTHON)"
export PYTHONHASHSEED=0 TOKENIZERS_PARALLELISM=false HF_ALLOW_CODE_EVAL=1 CUDA_VISIBLE_DEVICES=""
export HF_SCRIPTS_VERSION=${HF_SCRIPTS_VERSION:-v0.4.0}   # the verified code_eval module (see run_crb.sh)
go_offline() { export HF_HUB_OFFLINE=1 HF_DATASETS_OFFLINE=1 TRANSFORMERS_OFFLINE=1 HF_EVALUATE_OFFLINE=1; }
[ "${CRB_OFFLINE:-0}" = 1 ] && go_offline

mkdir -p "$OUT/buggy_datasets" "$OUT/logs" || fail "cannot create $OUT"
OUT=$(cd "$OUT" && pwd)
TAG=$(basename "${TOKENIZER%/}")
DEDUP_ARG=(); [ $DEDUP = 1 ] && DEDUP_ARG=(--deduplicate)

# the evaluator's datasets at the pinned revisions (generate.py reads the same datasets)
if [ "${CRB_OFFLINE:-0}" != 1 ]; then
  "$PY" "$HERE/crb_evaldata.py" prefetch --datasets "${DATASETS[@]}" > "$OUT/logs/evaldata_prefetch.log" 2>&1 \
    || fail "could not fetch the datasets (see $OUT/logs/evaldata_prefetch.log)"
  "$PY" -c "from transformers import AutoTokenizer as A;A.from_pretrained('$TOKENIZER',trust_remote_code=True,use_fast=False)" \
    > "$OUT/logs/tokenizer_download.log" 2>&1 || fail "could not load tokenizer $TOKENIZER"
fi
go_offline
EVALDATA=$("$PY" "$HERE/crb_evaldata.py" fingerprint --datasets "${DATASETS[@]}" 2>"$OUT/logs/evaldata.log" | tail -1)
echo "$EVALDATA" | grep -q '"mismatch": \[\]' || echo "WARNING: datasets differ from the pinned revisions: $EVALDATA"
grep -q '"code_eval_matches": true' <<< "$EVALDATA" \
  || fail "the code_eval metric module differs from the verified one (HF_SCRIPTS_VERSION=$HF_SCRIPTS_VERSION; see $OUT/logs/evaldata.log): $EVALDATA"

cd "$REPO" || exit 1
N=0
for NR in "${NR_ARR[@]}"; do for DS in "${DATASETS[@]}"; do for ET in "${ERROR_TYPES[@]}"; do
  ST=${TAG}_${ET}_${DATA_NUM}_wrong_${NR}
  RAW=$OUT/buggy_datasets/$DS/$ST.jsonl
  EV=$OUT/buggy_datasets/$DS/evaluated/${ST}_evaluated.jsonl
  [ -s "$EV" ] && continue
  (
    set -e
    mkdir -p "$(dirname "$EV")"
    "$PY" codecorrection/generate.py --dataset "$DS" --error_type "$ET" --model_name "$TOKENIZER" \
        --data_path "$OUT/buggy_datasets" --n_replace "$NR" --data_num "$DATA_NUM" --seed "$SEED" \
        "${DEDUP_ARG[@]}" > "$OUT/logs/generate_${DS}_${ET}_nr${NR}.log" 2>&1
    [ -s "$RAW" ]
    "$PY" evaluate_code.py --results_file "$RAW" --output_file "$EV.tmp" --dataset "$DS" \
        --map_prompt2completion --no_postprocess > "$OUT/logs/evaluate_${DS}_${ET}_nr${NR}.log" 2>&1
    mv "$EV.tmp" "$EV"
  ) || echo "FAILED: $DS $ET nr=$NR (logs in $OUT/logs)" &
  N=$((N+1))
  echo "[build] $DS $ET nr=$NR"
  while [ "$(jobs -rp | wc -l)" -ge "$EVAL_JOBS" ]; do wait -n; done
done; done; done
wait

NMISS=0
for NR in "${NR_ARR[@]}"; do for DS in "${DATASETS[@]}"; do for ET in "${ERROR_TYPES[@]}"; do
  [ -s "$OUT/buggy_datasets/$DS/evaluated/${TAG}_${ET}_${DATA_NUM}_wrong_${NR}_evaluated.jsonl" ] || NMISS=$((NMISS+1))
done; done; done
[ $NMISS = 0 ] || fail "$NMISS input files missing"

(cd "$OUT" && find buggy_datasets -path '*/evaluated/*_evaluated.jsonl' -name "${TAG}_*_${DATA_NUM}_wrong_*" | sort | xargs md5sum) > "$OUT/INPUTS.md5"
TOK=$("$PY" "$HERE/crb_tokcheck.py" "$TOKENIZER" "$OUT" --nr "${NR_ARR[@]}" --datasets "${DATASETS[@]}" \
      --error_types "${ERROR_TYPES[@]}" --tag "$TAG" --data_num "$DATA_NUM" 2>"$OUT/logs/tokcheck.log" | tail -1)
[ -n "$TOK" ] || fail "tokenizer check failed (see $OUT/logs/tokcheck.log)"
CRB_TOK=$TOK CRB_EVALDATA=$EVALDATA "$PY" - "$OUT" "$REPO" "$TOKENIZER" "$TAG" "$SEED" "$DATA_NUM" "$DEDUP" \
    "$NR_LIST" "$DATASETS_LIST" "$ERROR_TYPES_LIST" <<'PY' || fail "could not write crb_inputs_meta.json"
import hashlib, json, os, subprocess, sys
from pathlib import Path
out, repo, tokenizer, tag, seed, data_num, dedup, nr, dss, ets = sys.argv[1:11]
tok = json.loads(os.environ["CRB_TOK"])
files = {}
for line in open(Path(out) / "INPUTS.md5"):
    rel = line.split(None, 1)[1].strip()
    rows = [json.loads(l) for l in open(Path(out) / rel)]
    files[rel] = {"n": len(rows), "n_failing": sum(not r["test_passed"] for r in rows)}
commit = subprocess.run(["git", "-C", repo, "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
meta = {"tag": tag, "tokenizer": tokenizer, "seed": int(seed), "data_num": int(data_num),
        "deduplicate": dedup == "1", "nr": [int(x) for x in nr.split()], "datasets": dss.split(),
        "error_types": ets.split(), "token_sha256": tok["token_sha256"], "n_failing_total": tok["n_samples"],
        "n_error_pos_out_of_range": tok["n_error_pos_out_of_range"],
        "generate_py_sha256": hashlib.sha256(open(Path(repo) / "codecorrection/generate.py", "rb").read()).hexdigest(),
        "evaluate_code_py_sha256": hashlib.sha256(open(Path(repo) / "evaluate_code.py", "rb").read()).hexdigest(),
        "repo_commit": commit, "evaldata": json.loads(os.environ["CRB_EVALDATA"]), "files": files}
json.dump(meta, open(Path(out) / "crb_inputs_meta.json", "w"), indent=1)
print(f"[build] {len(files)} files, {tok['n_samples']} test-failing programs, token_sha256 {tok['token_sha256']}")
PY
echo "[build] done: $OUT (use CRB_INPUTS_DIR=$OUT with run_crb.sh)"
exit 0
}
